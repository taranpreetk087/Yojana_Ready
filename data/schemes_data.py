def validate_schemes(schemes=None):
    """
    Data-integrity check run whenever the scheme database is built. It exists
    because two real bugs came from data mistakes, not logic mistakes: a list
    that mixed "ALL" with specific codes (which silently excluded people), and
    a category code that the questionnaire could never produce. Fails loudly
    at build time instead of quietly at demo time.
    """
    schemes = SCHEMES if schemes is None else schemes
    required = {"id", "name", "category", "description", "benefit_summary", "min_age",
                "max_age", "income_max", "gender", "occupations", "special_categories",
                "states", "extra_conditions", "required_documents", "application_link"}
    valid = {
        "occupations": set(OCCUPATION_LABELS),
        "special_categories": set(CATEGORY_LABELS) | set(DERIVED_CATEGORIES),
        "employment": set(EMPLOYMENT_LABELS),
        "states": set(STATES),
    }
    problems, seen = [], set()
    for s in schemes:
        sid = s.get("id", "<no id>")
        if sid in seen:
            problems.append(f"{sid}: duplicate id")
        seen.add(sid)
        missing = required - set(s)
        if missing:
            problems.append(f"{sid}: missing fields {sorted(missing)}")
            continue
        if s["gender"] not in ("ALL", "female", "male", "other"):
            problems.append(f"{sid}: bad gender {s['gender']!r}")
        for field in ("occupations", "special_categories", "employment", "states"):
            values = s.get(field, ["ALL"])
            if not isinstance(values, list) or not values:
                problems.append(f"{sid}: {field} must be a non-empty list")
                continue
            if "ALL" in values and values != ["ALL"]:
                problems.append(f"{sid}: {field} mixes 'ALL' with specific values {values}")
            for v in values:
                if v != "ALL" and v not in valid[field]:
                    problems.append(f"{sid}: unknown {field} code {v!r}")
    if problems:
        raise ValueError("Scheme data problems:\n  " + "\n  ".join(problems))
    return True
